// Bundle the server into a single self-contained CommonJS file that the Godot
// client ships and launches with `node`. Output lands in the client's tree
// (client/server/debris-server.cjs) so it's packaged alongside the app.
//
// Run with `yarn bundle` (or `npm run bundle`).

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, "../src/index.ts");
const outfile = resolve(here, "../../client/server/debris-server.cjs");

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node18",
  // Keep it self-contained; the MongoDB driver's optional native add-ons are
  // required lazily and caught if absent, so nothing extra is needed at runtime.
  banner: {
    js: "// Generated by `yarn bundle` from the Debris server. Do not edit by hand.",
  },
});

console.log(`Bundled server -> ${outfile}`);
